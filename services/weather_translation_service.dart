  static String condition(String condition) {
    final text = condition.toLowerCase();

    if (text.contains('sun')) {
      return 'آفتابی';
    }

    if (text.contains('clear')) {
      return 'صاف';
    }

    if (text.contains('partly')) {
      return 'نیمه ابری';
    }

    if (text.contains('cloud')) {
      return 'ابری';
    }

    if (text.contains('rain')) {
      return 'بارانی';
    }

    if (text.contains('storm')) {
      return 'طوفانی';
    }

    if (text.contains('snow')) {
      return 'برفی';
    }

    if (text.contains('fog')) {
      return 'مه آلود';
    }

    return condition;
  }
